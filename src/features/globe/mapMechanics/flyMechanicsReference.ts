export function isMapMechanicsOnlyEnabled(search = typeof window !== "undefined" ? window.location.search : "") {
  const params = new URLSearchParams(search);
  const avatarDiag = params.get("avatarDiag");
  if (avatarDiag && avatarDiag !== "none" && avatarDiag !== "full") return false;
  if (params.get("avatarSource") === "mvt") return false;
  if (MAP_MECHANICS_ONLY) return true;
  return params.get("mapMechanicsOnly") === "1";
}

